SELECT 
	XTP.*	
FROM 
	SE5040 E5 
	INNER JOIN SE1040 E1 ON E1.E1_FILIAL = E5.E5_FILIAL AND E1.E1_NUM = E5.E5_NUMERO AND E1.E1_PREFIXO = E5.E5_PREFIXO AND E1.E1_PARCELA = E5.E5_PARCELA AND E1.D_E_L_E_T_ = ''
	INNER JOIN XTP040 XTP ON XTP.XTP_FILIAL = E1.E1_FILIAL AND XTP.XTP_IDPAY = E1.E1_DOCTEF AND XTP.XTP_PARC = IIF(E1.E1_PARCELA = '','01',E1.E1_PARCELA) AND XTP.D_E_L_E_T_ = ''
WHERE 
	E5.E5_FILIAL =  '0404' AND
	E5.E5_DOCUMEN = '006368' AND 
	E5.D_E_L_E_T_ = ''