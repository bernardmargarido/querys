SELECT 
	AY1.AY1_CODIGO, 
	AY1.AY1_SUBCAT, 
	AY0.AY0_DESC, 
	AY0.AY0_STATUS, 
	AY1.AY1_CATPAI, 
	AY1.AY1_CATFIL, 
	AY0.AY0_CODDES, 
(	SELECT 
		SZ0.Z0_ID 
	FROM 
		SZ0010 SZ0 
	WHERE 
		SZ0.Z0_FILIAL = '  ' AND 
		SZ0.Z0_ALIAS = 'AY0' AND 
		SZ0.Z0_CODERP = AY1.AY1_SUBCAT AND 
		SZ0.D_E_L_E_T_ = '' 
	) IDCATEG, 		AY0.R_E_C_N_O_ RECNOAY0 
FROM 
	 AY1010 AY1 
	INNER JOIN AY0010 AY0 ON AY0.AY0_CODIGO = AY1.AY1_SUBCAT AND AY0.AY0_XMSEXP = '' AND AY0.D_E_L_E_T_ = '' 
WHERE 
	AY1.D_E_L_E_T_ = ' ' 
ORDER BY AY0_TIPO 
