SELECT 
	CONTA,
	( ( (SALDODEBITO + SALDOANTERIORDEBITO)  - (  SALDOANTERIORCREDITO + SALDOCREDITO ) ) * (-1)) SALDO
FROM 
(
	SELECT 
		CQ1.CQ1_CONTA AS CONTA,
		SUM(CASE WHEN CQ1.CQ1_DATA < '20250601' AND CQ1_TPSALD = '1' AND CQ1_MOEDA = '01' THEN CQ1.CQ1_DEBITO ELSE 0 END ) AS SALDOANTERIORDEBITO,
		SUM(CASE WHEN CQ1.CQ1_DATA < '20250601' AND CQ1_TPSALD = '1' AND CQ1_MOEDA = '01' THEN CQ1.CQ1_CREDIT ELSE 0 END ) AS SALDOANTERIORCREDITO,
		SUM(CASE WHEN CQ1.CQ1_DATA BETWEEN '20250601' AND '20250630' AND CQ1_TPSALD = '1' AND CQ1_MOEDA = '01' THEN CQ1.CQ1_DEBITO ELSE 0 END  ) AS SALDODEBITO,
		SUM(CASE WHEN CQ1.CQ1_DATA BETWEEN '20250601' AND '20250630' AND CQ1_TPSALD = '1' AND CQ1_MOEDA = '01' THEN CQ1.CQ1_CREDIT ELSE 0 END  ) AS SALDOCREDITO
	FROM CQ1010 CQ1 (NOLOCK)
	WHERE 
		CQ1_FILIAL IN ('0101','0102','0103') 
		AND CQ1.CQ1_MOEDA = '01'
		AND CQ1.CQ1_TPSALD = '1'
		AND CQ1_CONTA IN('1.010101001','1.010102001','2.010201001','3.010101001')
		AND CQ1.D_E_L_E_T_ = ''
	GROUP BY CQ1.CQ1_CONTA
)SALDOCONTA