					COALESCE(DA1.DA1_XXPVNZ, 0 ) DA1_XXPVNZ
				FROM 
					SC5010 C5 
					LEFT JOIN DA1010 DA1 (NOLOCK) ON DA1.DA1_FILIAL = C5.C5_FILIAL AND DA1.DA1_CODTAB = C5.C5_TABELA AND DA1.DA1_CODPRO = D2.D2_COD AND DA1.D_E_L_E_T_ = ''
				WHERE 
					C5.C5_FILIAL = D2.D2_FILIAL AND 
					C5.C5_NUM = D2.D2_PEDIDO AND 
					C5.D_E_L_E_T_ = ''
			)GRUPO_RECURSOS
		WHERE 
			D2.D2_FILIAL + D2.D2_DOC + D2.D2_SERIE = '0101010003074033' AND  
			D2.D_E_L_E_T_ = '' 
		GROUP BY D2.D2_FILIAL,D2.D2_DOC, D2.D2_SERIE, D2.D2_EMISSAO, D2.D2_COD
		UNION ALL 
		-- LITOGRAFIA
		SELECT 
			D2.D2_FILIAL FILIAL, 
			D2.D2_DOC DOCUMENTO, 
			D2.D2_SERIE SERIE, 
			D2.D2_EMISSAO EMISSAO, 
			'LITOGRAFIA' PRODUTO,
			SUM(CASE WHEN GRUPO_RECURSOS.DA1_XXPLIT > 0 THEN ROUND(D2.D2_VALBRUT * (GRUPO_RECURSOS.DA1_XXPLIT /100 ),2) ELSE 0 END ) VALOR_CALC, 
			SUM(CASE WHEN GRUPO_RECURSOS.DA1_XXPLIT > 0 THEN ROUND((D2.D2_VALICM + D2.D2_VALIPI + D2.D2_VALIMP5 + D2.D2_VALIMP6) * (GRUPO_RECURSOS.DA1_XXPLIT /100 ),2)ELSE 0 END ) IMP_CALC, 
			SUM(CASE WHEN GRUPO_RECURSOS.DA1_XXPLIT > 0 THEN ROUND(D2.D2_CUSTO1 * (GRUPO_RECURSOS.DA1_XXPLIT /100 ),2) ELSE 0 END )  CPV_CALC, 
			SUM(CASE WHEN GRUPO_RECURSOS.DA1_XXPLIT > 0 THEN COALESCE(ROUND(ROUND(ROTEIRO.CUSTO_MO * D2.D2_QUANT,2) * (GRUPO_RECURSOS.DA1_XXPLIT /100 ),2),0) ELSE 0 END ) CUSTO_MO_CALC
		FROM 
			SD2010 D2 
			OUTER APPLY( 
				SELECT 
					SUBSTRING(G2.G2_PRODUTO,1,18) G2_PRODUTO, 
					SUM(CASE WHEN H1.H1_XCSTUNI > 0 THEN ROUND(H1.H1_XCSTUNI * IIF(B1.B1_QBP > 0, B1.B1_QBP, 1) ,4) ELSE 0 END) CUSTO_MO 
				FROM 
					SG2010 G2 
					INNER JOIN SB1010 B1 (NOLOCK) ON B1.B1_FILIAL = '' AND B1.B1_COD = D2.D2_COD AND B1.B1_TIPO = 'PA' AND B1.D_E_L_E_T_ = '' 
					INNER JOIN SH1010 H1 (NOLOCK) ON H1.H1_FILIAL = G2.G2_FILIAL AND H1.H1_CODIGO = G2.G2_RECURSO AND H1.D_E_L_E_T_ = '' 
				WHERE 
					G2.G2_FILIAL = D2.D2_FILIAL AND 
					SUBSTRING(G2.G2_PRODUTO,1,18) LIKE '%'+ SUBSTRING(D2.D2_COD,1,18) +'%' AND 
					G2.G2_RECURSO NOT IN('EMBLIT') AND 
					G2.D_E_L_E_T_ = '' 
				GROUP BY SUBSTRING(G2.G2_PRODUTO,1,18) 
			) ROTEIRO 
			OUTER APPLY (
				SELECT 
					DA1.DA1_XXPLIT
				FROM 
					SC5010 C5 
					LEFT JOIN DA1010 DA1 (NOLOCK) ON DA1.DA1_FILIAL = C5.C5_FILIAL AND DA1.DA1_CODTAB = C5.C5_TABELA AND DA1.DA1_CODPRO = D2.D2_COD AND DA1.D_E_L_E_T_ = ''
				WHERE 
					C5.C5_FILIAL = D2.D2_FILIAL AND 
					C5.C5_NUM = D2.D2_PEDIDO AND 
					C5.D_E_L_E_T_ = ''
			)GRUPO_RECURSOS
		WHERE 
			D2.D2_FILIAL + D2.D2_DOC + D2.D2_SERIE = '0101010003074033' AND 
			D2.D_E_L_E_T_ = '' 
		GROUP BY D2.D2_FILIAL,D2.D2_DOC, D2.D2_SERIE, D2.D2_EMISSAO, D2.D2_COD
	)CALCULOS_GRUPOS
	GROUP BY FILIAL, DOCUMENTO, SERIE, EMISSAO, PRODUTO
