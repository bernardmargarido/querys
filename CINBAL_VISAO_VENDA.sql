-- CONSOLIDADO FILIAL
SELECT 
	FILIAL, 
	NOME_FILIAL,
	QUANTIDADE,
	VALOR_BRUTO,
	IMPOSTOS,
	CPV,
	CUSTOMO,
	ROUND(VALOR_BRUTO - IMPOSTOS - CPV - CUSTOMO,2) VENDA_LIQUIDA,
	ROUND( ( (VALOR_BRUTO - IMPOSTOS - CPV - CUSTOMO) / VALOR_BRUTO) * 100 , 2 ) MARGEM
FROM(
	SELECT 
		F2.F2_FILIAL FILIAL, 
		COMP.M0_FILIAL NOME_FILIAL,
		SUM(QUANTIDADE.D2_QUANT) QUANTIDADE,
		SUM(F2.F2_VALBRUT) VALOR_BRUTO,
		SUM(F2.F2_VALICM + F2.F2_VALIPI + F2.F2_VALIMP5 + F2.F2_VALIMP6 ) IMPOSTOS,
		SUM(QUANTIDADE.D2_CUSTO1) CPV,
		SUM(QUANTIDADE.CUSTO_MO) CUSTOMO
	FROM 
		SF2010 F2 
		INNER JOIN SYS_COMPANY COMP (NOLOCK) ON M0_CODIGO = '01' AND M0_CODFIL = F2.F2_FILIAL AND COMP.D_E_L_E_T_ = ''
		CROSS APPLY(
			SELECT 
				D2.D2_QUANT,
				D2.D2_CUSTO1,
				ROUND(ROTEIRO.CUSTO_MO * D2.D2_QUANT,2) CUSTO_MO
			FROM 
				SD2010 D2 
				OUTER APPLY(
					SELECT 
						SUBSTRING(G2.G2_PRODUTO,1,18) G2_PRODUTO,
						SUM(CASE WHEN H1.H1_XCSTUNI > 0 THEN ROUND(H1.H1_XCSTUNI * IIF(B1.B1_QBP > 0, B1.B1_QBP, 1) ,4) ELSE 0 END) CUSTO_MO
					FROM 
						SG2010 G2 
						INNER JOIN SB1010 B1 (NOLOCK) ON B1.B1_FILIAL = '' AND B1.B1_COD = D2.D2_COD AND B1.B1_TIPO = 'PA' AND B1.D_E_L_E_T_ = ''
						INNER JOIN SH1010 H1 (NOLOCK) ON H1.H1_FILIAL = G2.G2_FILIAL AND H1.H1_CODIGO = G2.G2_RECURSO AND H1.D_E_L_E_T_ = ''
					WHERE 
						G2.G2_FILIAL = D2.D2_FILIAL AND 
						SUBSTRING(G2.G2_PRODUTO,1,18) LIKE '%'+ SUBSTRING(D2.D2_COD,1,18) +'%' AND 
						G2.G2_RECURSO NOT IN('EMBLIT') AND
						G2.D_E_L_E_T_ = ''
					GROUP BY SUBSTRING(G2.G2_PRODUTO,1,18)
				) ROTEIRO
			WHERE 
				D2.D2_FILIAL = F2.F2_FILIAL AND 
				D2.D2_DOC = F2.F2_DOC AND 
				D2.D2_SERIE = F2.F2_SERIE AND 
				D2.D_E_L_E_T_ = ''
		)QUANTIDADE
	WHERE 
		F2.F2_FILIAL BETWEEN '      ' AND 'ZZZZZZ' AND 
		F2.F2_EMISSAO BETWEEN '20230101' AND '20231231' AND 
		F2.F2_TIPO = 'N' AND 
		F2.D_E_L_E_T_ = ''
	GROUP BY F2.F2_FILIAL, COMP.M0_FILIAL
)CONSOLIDADO_FILIAL
ORDER BY FILIAL

