SELECT
	A2_CGC,
	'EXTERNO BUNZL',
	'',
	A2_CONTATO,
	A2_INSCRM,
	A2_CGC,
	A2_COD,
	A2_LOJA,
	'004',
	A2_CGC,
	A2_NOME,
	CASE WHEN CharIndex(';', A2_EMAIL) > 0 THEN RTRIM(SUBSTRING(A2_EMAIL,1,CharIndex(';', A2_EMAIL) - 1)) ELSE RTRIM(A2_EMAIL) END A2_EMAIL,
	A2_DDD,
	A2_TEL
FROM 
	SA2010 A2 
	LEFT JOIN SX5010 X5 ON X5.X5_FILIAL = '0404' AND X5_TABELA = '58' AND X5_CHAVE = A2.A2_FORMPAG AND X5.D_E_L_E_T_ = ''
WHERE 
	A2_TIPO = 'J' AND 
	( A2_CGC <> '' AND A2_CGC <> '00000000000000' ) AND
	A2.D_E_L_E_T_ = '' 
