 SELECT 
	G1.G1_FILIAL FILIAL, 
	ESTRUTURA_SG2.G2_PRODUTO PRODUTO, 
	ESTRUTURA_SG2.B1_QBP QTD_BASE, 
	G1.G1_COMP COMPLEMENTAR, 
	COMPLEMENTAR.B1_DESC DESCRICAO_COMPLEMENTAR, 
	G1.G1_QUANT QTD_NECESSARIA, 
	CUSTO_ENTRADA.D1_DOC DOCUMENTO, 
	CUSTO_ENTRADA.D1_SERIE SERIE, 
	CASE WHEN CUSTO_ENTRADA.D1_CUSTO > 0 THEN ROUND( CUSTO_ENTRADA.D1_CUSTO / CUSTO_ENTRADA.D1_QUANT, 2 ) ELSE 0 END CUSTO_UNITARIOO,
	CASE WHEN CUSTO_ENTRADA.D1_CUSTO > 0 THEN ROUND(ROUND( CUSTO_ENTRADA.D1_CUSTO / CUSTO_ENTRADA.D1_QUANT, 4 ) * G1.G1_QUANT,4) ELSE 0 END CUSTO_TOTAL
 FROM 
	SG1010 G1 (NOLOCK) 
    CROSS APPLY ( 
		SELECT 
			TOP 1 
			G2.G2_PRODUTO, 
			B1.B1_DESC, 
			B1.B1_QBP 
		FROM 
			SG2010 G2 (NOLOCK) 
			INNER JOIN SB1010 B1 (NOLOCK) ON B1.B1_FILIAL = '      ' AND B1.B1_COD = G2.G2_PRODUTO AND B1.B1_TIPO = 'PA' AND B1.D_E_L_E_T_ = '' 
		WHERE 
			G2.G2_FILIAL = G1.G1_FILIAL AND 
			SUBSTRING(G2.G2_PRODUTO,1,18) LIKE '%'+ SUBSTRING(G1.G1_COD,1,18) +'%' AND 
			G2.G2_RECURSO NOT IN('EMBLIT') AND 
			G2.D_E_L_E_T_ = '' 
		ORDER BY G2.G2_FILIAL, G2.G2_OPERAC DESC 
	) ESTRUTURA_SG2 
	CROSS APPLY ( 
		SELECT 
			B1.B1_COD, 
			B1.B1_DESC,
			B1.B1_TIPO
		FROM 
			SB1010 B1 
		WHERE 
			B1.B1_FILIAL = '      ' AND 
			B1.B1_COD  = G1.G1_COMP AND 
			B1.B1_TIPO <> 'MO' AND 
			B1.D_E_L_E_T_ = '' 
	) COMPLEMENTAR 
	CROSS APPLY ( 
		SELECT 
			TOP 1 
			D1.D1_FILIAL, 
			D1.D1_COD, 
			D1.D1_DOC, 
			D1.D1_SERIE, 
			D1.D1_DTDIGIT, 
			SUM(D1.D1_CUSTO) D1_CUSTO, 
			SUM(D1.D1_QUANT) D1_QUANT 
		FROM 
			SD1010 D1 
			INNER JOIN SB1010 B1 (NOLOCK) ON  B1.B1_FILIAL = '' AND B1.B1_COD  = G1.G1_COMP AND	B1.B1_TIPO <> 'MO' AND	B1.D_E_L_E_T_ = ''
		WHERE 
			D1.D1_FILIAL = G1.G1_FILIAL AND 
			D1.D1_COD = COMPLEMENTAR.B1_COD AND 
			D1.D1_DTDIGIT <= '20240228' AND 
			D1.D_E_L_E_T_ = '' 
		GROUP BY D1.D1_FILIAL,D1.D1_COD,D1.D1_DOC,D1.D1_SERIE,D1.D1_DTDIGIT 
		ORDER BY D1.D1_DTDIGIT DESC 
	)CUSTO_ENTRADA 
 WHERE 
	G1.G1_COD BETWEEN '33000000000023902960' AND '33000000000023902964' AND 
	G1.D_E_L_E_T_ = '' 
 ORDER BY G1.G1_FILIAL,G1.G1_COD 
