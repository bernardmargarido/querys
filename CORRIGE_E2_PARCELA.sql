SELECT 
    E2_PARCELA AS ORIGINAL,
    CASE 
        WHEN E2_PARCELA BETWEEN '0' AND '9'
            THEN '0' + E2_PARCELA
        ELSE RIGHT('00' + CAST(10 + ASCII(E2_PARCELA) - ASCII('A') AS VARCHAR(2)), 2)
    END AS NOVO
FROM SE2010
WHERE 
    E2_NUM IN('000063185','000063438','000063448','000063455','000063456',
               '000063457','000063458','000063459','000217532')
    AND D_E_L_E_T_ = '';

begin transaction;
UPDATE SE2010
SET E2_PARCELA = 
    CASE 
        WHEN E2_PARCELA BETWEEN '0' AND '9'
            THEN'0' + E2_PARCELA

        ELSE RIGHT('00' + CAST(10 + ASCII(E2_PARCELA) - ASCII('A') AS VARCHAR(2)), 2)
    END
WHERE 
    E2_NUM IN('000063185','000063438','000063448','000063455','000063456',
               '000063457','000063458','000063459','000217532')
    AND D_E_L_E_T_ = '';
commit;



