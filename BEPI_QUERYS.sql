-- CATEGORIAS
SELECT 
	CATEG_PAI.ACU_COD CODPAI,
	CATEG_PAI.ACU_XIDLV IDVTPAI,
	ACU.ACU_FILIAL,
	ACU.ACU_COD,
	ACU.ACU_DESC,
	ACU.ACU_XTITUL,
	ACU.ACU_XKWORD,
	ACU.ACU_XLCMPC,
	ACU.ACU_XREMAR,
	ACU.ACU_XIDLV,
	ACU.R_E_C_N_O_ RECNOACU
FROM 
	ACU010 ACU (NOLOCK)
	OUTER APPLY(
		SELECT 
			ACU_PAI.ACU_COD,
			ACU_PAI.ACU_XIDLV
		FROM 
			ACU010 ACU_PAI (NOLOCK)
		WHERE 
			ACU.ACU_FILIAL = '' AND 
			ACU_PAI.ACU_COD = ACU.ACU_CODPAI AND 
			ACU_PAI.D_E_L_E_T_ = ''
	) CATEG_PAI
WHERE 
	ACU.ACU_FILIAL = '' AND 
	ACU.ACU_XINTLV = '2' AND
	ACU.D_E_L_E_T_ = ''
ORDER BY ACU.ACU_CODPAI,ACU.ACU_COD

