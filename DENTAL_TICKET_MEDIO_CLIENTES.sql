SELECT 
	CLIENTE,
	LOJA,
	MEDIA 
FROM 
	(
	SELECT 
		A1.A1_COD CLIENTE,
		A1.A1_LOJA LOJA,
		CALCULA_MEDIA.MEDIA MEDIA
	FROM 
		SA1050 A1 (NOLOCK) 
		CROSS APPLY(
			SELECT
				CLIENTE,
				LOJA, 
				SUM(QRY_B.VALOR_NOTA) / 3 MEDIA
			FROM (
				SELECT
					TOP 3
					CLIENTE,
					LOJA, 
					QRY_A.VALOR_NOTA VALOR_NOTA,
					QRY_A.FATURADOS FATURADOS
				FROM (
					SELECT 
						TOP 4
						ROW_NUMBER() OVER(PARTITION BY D2.D2_CLIENTE ORDER BY D2.D2_CLIENTE,D2.D2_LOJA ) FATURADOS,
						D2.D2_CLIENTE CLIENTE,
						D2.D2_LOJA LOJA, 
						SUBSTRING(D2.D2_EMISSAO, 5, 2) + '_VLR' MES_VALOR,
						SUM(D2.D2_VALBRUT - D2.D2_ICMSRET - D2.D2_VALIPI - D2.D2_VALISS - D2.D2_VALIMP5 - D2.D2_VALIMP6 - D2.D2_VALICM + D2.D2_DESCICM - D2.D2_DIFAL - D2.D2_ICMSCOM - D2.D2_VFCPDIF) VALOR_NOTA
					FROM 
						SD2050 D2 (NOLOCK) 
					WHERE 
						D2.D2_FILIAL BETWEEN '    ' AND 'ZZZZ' AND 
						D2.D2_EMISSAO BETWEEN '20230331'  AND '20240331' AND
						D2.D2_TIPO NOT IN  ('D','B') AND
						D2.D2_CF IN('5102','6403','5403','5405','6405','5404','5401','6401','6102','6108','6404','6405','5108' ) AND
						D2.D2_CLIENTE = A1.A1_COD AND 
						D2.D2_LOJA = A1.A1_LOJA AND
						D2.D_E_L_E_T_ = ''
					GROUP BY D2.D2_CLIENTE, D2.D2_LOJA, SUBSTRING(D2_EMISSAO, 5, 2)
					ORDER BY D2.D2_CLIENTE, D2.D2_LOJA, VALOR_NOTA DESC 
				)QRY_A
				ORDER BY CLIENTE, LOJA, QRY_A.VALOR_NOTA ASC
			) QRY_B
			GROUP BY CLIENTE, LOJA HAVING COUNT(QRY_B.FATURADOS) > 2
		) CALCULA_MEDIA
	WHERE 
		A1.A1_FILIAL = '' AND 
		A1.A1_COD BETWEEN '000018' AND '114316' AND 
		A1.A1_LOJA BETWEEN '' AND 'ZZZZ' AND 
		A1.D_E_L_E_T_ = ''
) MEDIA
ORDER BY CLIENTE, LOJA
